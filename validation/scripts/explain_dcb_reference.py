"""Explain the existing DCB curves without changing their data or assumptions."""
import argparse
import json
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

from campaign import CAMPAIGN
from lefm_reference import dcb
from reduce_structure import rows


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,default=CAMPAIGN/'results/explanation_03')
    args=parser.parse_args();args.out.mkdir(parents=True,exist_ok=False)
    folder=CAMPAIGN/'runs/dcb_ps03';manifest=json.loads((folder/'run.json').read_text());p=manifest['parameters']
    peak,opening,compliance=dcb(p['a'],p['E'][0],p['b'],p['h'],p['G'][0])
    analytical=np.array([[float(r[k]) for k in ['displacement_mm','load_N']] for r in rows(folder/'assessment/lefm_equilibrium.csv')])
    computed=np.array([[float(r[k]) for k in ['displacement_mm','total_force_N']] for r in rows(folder/'assessment/force_displacement.csv')])
    observed=np.array([[float(r[k]) for k in ['opening_mm','load_N']] for r in rows(CAMPAIGN/'reference_data/turon2010CS_dcb/fig04_tau30_graphical.csv')])
    metrics=json.loads((folder/'assessment/metrics.json').read_text())
    elastic=next(r for r in json.loads((CAMPAIGN/'results/fixed_crack_checks.json').read_text()) if r['name']=='fixed_dcb_a35p0')
    summary=dict(inputs=dict(a0_mm=p['a'],arm_thickness_mm=p['h'],width_mm=p['b'],E11_MPa=p['E'][0],GIc_N_per_mm=p['G'][0]),
        elementary_beam=dict(compliance_mm_per_N=float(compliance),stiffness_N_per_mm=float(1/compliance),initiation_load_N=float(peak),initiation_opening_mm=float(opening)),
        elastic_FE_fixed_crack=dict(compliance_mm_per_N=elastic['elastic_compliance_mm_per_N'],stiffness_N_per_mm=1/elastic['elastic_compliance_mm_per_N'],initiation_load_N=elastic['critical_load_N'],initiation_opening_mm=elastic['critical_displacement_mm'],scope='Independent linear C3D8I plane-strain slice, tied crack tip, VCCT; no active UEL'),
        UEL=dict(early_load_compliance_mm_per_N=metrics['initial_compliance_mm_per_N'],early_load_stiffness_N_per_mm=1/metrics['initial_compliance_mm_per_N'],recorded_maximum_load_N=metrics['maximum_reached_force_N'],opening_at_recorded_maximum_mm=metrics['displacement_at_maximum_reached_force_mm']),
        scope='Explanation of the first-campaign figure03; no fitted crack-length/root correction, new solver run, or replacement of any original curve')
    (args.out/'comparison.json').write_text(json.dumps(summary,indent=2)+'\n')
    plt.rcParams.update({'font.family':'DejaVu Serif','font.size':8,'axes.labelsize':8,'legend.fontsize':6.3,'xtick.labelsize':7,'ytick.labelsize':7,'svg.fonttype':'none','pdf.fonttype':42})
    fig,ax=plt.subplots(figsize=(180/25.4,92/25.4),layout='constrained')
    ax.plot(computed[:,0],computed[:,1],color='#267d86',lw=1.2,label='UEL: 3D constrained slice, 0.30 mm mesh')
    ax.plot(observed[:,0],observed[:,1],color='#555555',ls=':',lw=1.,label='Published numerical curve, 30 MPa (graphical)')
    ax.fill_between(observed[:,0],observed[:,1]-.8,observed[:,1]+.8,color='#555555',alpha=.10,lw=0)
    ax.plot([0,opening],[0,peak],color='#aa6835',ls='--',lw=1.,label='Elementary beam: elastic line from C(a₀)')
    ax.plot(analytical[:,0],analytical[:,1],color='#aa6835',ls='-.',lw=1.,label='Elementary beam: LEFM growth, a ≥ a₀')
    ax.plot(opening,peak,'o',color='#aa6835',ms=4)
    ax.annotate('Ideal-beam initiation\n%.2f N at %.3f mm'%(peak,opening),xy=(opening,peak),xytext=(.72,62),fontsize=7,
        arrowprops=dict(arrowstyle='-',color='#aa6835',lw=.7))
    maximum=computed[np.argmax(computed[:,1])]
    ax.plot(*maximum,'o',color='#267d86',ms=4)
    ax.annotate('UEL recorded maximum\n%.2f N at %.3f mm'%(maximum[1],maximum[0]),xy=maximum,xytext=(2.93,61.5),fontsize=7,
        arrowprops=dict(arrowstyle='-',color='#267d86',lw=.7))
    ax.plot(elastic['critical_displacement_mm'],elastic['critical_load_N'],marker='D',ls='none',color='#78639a',mfc='white',mec='#78639a',ms=5,
        label='Elastic FE/VCCT initiation point; no active UEL')
    ax.annotate('%.2f N'%elastic['critical_load_N'],xy=(elastic['critical_displacement_mm'],elastic['critical_load_N']),xytext=(1.64,46),fontsize=7,color='#78639a',
        arrowprops=dict(arrowstyle='-',color='#78639a',lw=.7))
    ax.set(xlabel='Full relative opening [mm]',ylabel='Force on one arm [N]',xlim=(0,4.1),ylim=(0,68))
    ax.spines[['top','right']].set_visible(False);ax.legend(frameon=False,loc='lower right')
    for extension in ['png','pdf','svg']:fig.savefig(args.out/('03_dcb_reference_explained.'+extension),dpi=300)
    plt.close(fig)
    (args.out/'README.md').write_text('''# Explanation of DCB figure03

Generated by `validation/scripts/explain_dcb_reference.py` from retained campaign data.
The elementary-beam curve uses Turon2010 Appendix A1–A2 exactly as printed.
The straight elastic line is constructed from C(a0); the growth branch is parameterized
by crack length a≥a0. The corner is an ideal sharp-crack initiation prediction.
It is not the published cohesive-model peak. The latter is the separate grey curve.

The diamond comes from the existing fixed-crack elastic FE/VCCT control and is
an initiation estimate, not a cohesive propagation curve. It demonstrates that a
compliance difference exists before activating the UEL. Root rotation, shear and
dimensional assumptions need separate controlled checks before allocating that gap.
No crack length, modulus, toughness, force or displacement has been fitted or shifted.
The original figure03 and its data are preserved. See comparison.json for numbers.
''')
    print(json.dumps(summary,indent=2))


if __name__=='__main__':main()
